"""Plan an upgrade of a generated repository to a newer template commit.

``plan`` is read-only: it reads ``template.json``, resolves the old and new
template commits and reports why an upgrade cannot proceed. It never imports
``cookiecutter`` and never writes. Rendering and applying come later
(``docs/upgrading.md``).
"""

from __future__ import annotations

import json
import re
import shutil
import subprocess
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

from .diagnostics import Diagnostics
from .metadata import _metadata_schema

STAMP_NAME = "template.json"
GIT_TIMEOUT = 30
RENDER_TIMEOUT = 300
# Left out of both renders: the root stamp is rewritten by the upgrade, the rest is noise.
_NOISE = shutil.ignore_patterns(".git", "__pycache__", "*.pyc")


def _ignored(top: Path):
    """Ignore function for copytree: noise everywhere, the stamp only at the root."""
    top = Path(top)

    def ignore(directory: str, names: list[str]) -> set[str]:
        skipped = set(_NOISE(directory, names))
        if Path(directory) == top and STAMP_NAME in names:
            skipped.add(STAMP_NAME)
        return skipped

    return ignore

E_NO_STAMP = "U001"
E_BAD_STAMP = "U002"
E_NO_COMMIT = "U003"
E_NOT_GIT = "U004"
E_DIRTY = "U005"
E_V1_METADATA = "U006"
E_TEMPLATE_UNREACHABLE = "U007"
E_REF_UNKNOWN = "U008"
E_NO_COOKIECUTTER = "U009"
E_CHECKOUT = "U010"
E_RENDER = "U011"
E_NOT_READY = "U012"
E_BRANCH_EXISTS = "U013"
E_NO_UPGRADE = "U014"
E_CONFLICTS = "U015"
E_CHECKS_FAILED = "U016"
E_WRONG_BRANCH = "U017"
STATE_NAME = "upgrade-state.json"
TRACKED_STATE = ".upgrade-state.json"
E_COMMIT = "U018"
E_DRIFT = "U019"

_SHA = re.compile(r"[0-9a-f]{7,40}")
_FULL_SHA = re.compile(r"[0-9a-f]{40}")


@dataclass(frozen=True)
class Refusal:
    """A reason the upgrade cannot proceed, with a stable code."""

    code: str
    message: str

    def to_dict(self) -> dict[str, str]:
        return {"code": self.code, "message": self.message}


def _git(args: list[str], cwd: Path) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["git", *args],
        cwd=cwd,
        capture_output=True,
        text=True,
        timeout=GIT_TIMEOUT,
    )


def _read_stamp(root: Path) -> tuple[dict[str, Any] | None, Refusal | None]:
    path = root / STAMP_NAME
    if not path.is_file():
        return None, Refusal(
            E_NO_STAMP,
            f"{STAMP_NAME} not found: this repository was not generated by a stamping "
            "template version; use the manual procedure in docs/upgrading.md",
        )
    try:
        stamp = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        return None, Refusal(E_BAD_STAMP, f"{STAMP_NAME} is not valid JSON: {exc}")
    outer = stamp.get("context") if isinstance(stamp, dict) else None
    context = outer.get("cookiecutter") if isinstance(outer, dict) else None
    template = stamp.get("template") if isinstance(stamp, dict) else None
    if not isinstance(template, str) or not template or not isinstance(context, dict):
        return None, Refusal(
            E_BAD_STAMP, f"{STAMP_NAME} must hold `template` and `context.cookiecutter`"
        )
    return stamp, None


def _location(root: Path, template: str) -> str:
    """Make a relative local template path absolute, so it means the same in any cwd."""
    if "://" in template or re.match(r"^[\w.-]+@[\w.-]+:", template):
        return template
    local = root / template
    return str(local.resolve()) if local.exists() else template


def _resolve_new(
    root: Path, template: str, new_ref: str | None
) -> tuple[str | None, Refusal | None]:
    """Resolve the commit to upgrade to. A hex ref is taken as given."""
    ref = new_ref or "HEAD"
    if new_ref and _SHA.fullmatch(new_ref):
        return new_ref, None
    try:
        remote = _location(root, template)
        result = _git(["ls-remote", "--", remote, "HEAD", "refs/heads/*", "refs/tags/*"], root)
    except (OSError, subprocess.TimeoutExpired) as exc:
        return None, Refusal(E_TEMPLATE_UNREACHABLE, f"cannot reach template {template}: {exc}")
    if result.returncode != 0:
        detail = result.stderr.strip().splitlines()[-1:] or ["git ls-remote failed"]
        return None, Refusal(
            E_TEMPLATE_UNREACHABLE, f"cannot reach template {template}: {detail[0]}"
        )
    refs: dict[str, str] = {}
    for line in result.stdout.splitlines():
        sha, _, name = line.partition("\t")
        if _FULL_SHA.fullmatch(sha):
            refs[name] = sha
    # Exact names only; an annotated tag resolves to the commit it points at (`^{}`).
    candidates = ["HEAD"] if ref == "HEAD" else [
        f"refs/heads/{ref}", f"refs/tags/{ref}^{{}}", f"refs/tags/{ref}",
    ]
    for name in candidates:
        if name in refs:
            return refs[name], None
    return None, Refusal(E_REF_UNKNOWN, f"template {template} has no ref {ref!r}")


def _metadata_is_v1(root: Path) -> bool:
    try:
        data = yaml.safe_load((root / "metadata.yaml").read_text(encoding="utf-8")) or {}
    except (OSError, yaml.YAMLError):
        return False
    if not isinstance(data, dict):
        return False
    return _metadata_schema(data, Diagnostics()) == 1


def plan(root: Path, new_ref: str | None = None) -> dict[str, Any]:
    """Return a read-only upgrade plan for the repository at ``root``."""
    root = Path(root).resolve()
    refusals: list[Refusal] = []
    stamp, refusal = _read_stamp(root)
    if refusal:
        refusals.append(refusal)

    template = stamp["template"] if stamp else None
    old = stamp.get("template_commit") if stamp else None
    if stamp and not (isinstance(old, str) and old):
        refusals.append(
            Refusal(
                E_NO_COMMIT,
                "template_commit is null: the template was not a git checkout when this "
                "repository was generated, so the old version cannot be re-rendered",
            )
        )
        old = None

    new: str | None = None
    if template:
        new, refusal = _resolve_new(root, template, new_ref)
        if refusal:
            refusals.append(refusal)

    inside = _git(["rev-parse", "--is-inside-work-tree"], root)
    if inside.returncode != 0:
        refusals.append(
            Refusal(E_NOT_GIT, "not a git repository; commit the work before upgrading")
        )
    elif _git(["status", "--porcelain"], root).stdout.strip():
        refusals.append(
            Refusal(E_DIRTY, "working tree has uncommitted changes; commit or stash them first")
        )

    if _metadata_is_v1(root):
        refusals.append(
            Refusal(
                E_V1_METADATA,
                "metadata.yaml is schema 1; follow docs/migrating-to-v2.md before upgrading",
            )
        )

    up_to_date = bool(old and new and (old.startswith(new) or new.startswith(old)))
    return {
        "ok": not refusals,
        "command": "upgrade",
        "plan": {
            "template": template,
            "template_version": stamp.get("template_version") if stamp else None,
            "old": old,
            "new": new,
            "up_to_date": up_to_date,
        },
        "refusals": [r.to_dict() for r in refusals],
    }


class UpgradeError(Exception):
    """A user-actionable upgrade failure with a stable code."""

    def __init__(self, code: str, message: str) -> None:
        super().__init__(message)
        self.code = code
        self.message = message


def _run(args: list[str], cwd: Path, timeout: int) -> subprocess.CompletedProcess[str]:
    return subprocess.run(args, cwd=cwd, capture_output=True, text=True, timeout=timeout)


def _tail(result: subprocess.CompletedProcess[str]) -> str:
    lines = (result.stderr or result.stdout).strip().splitlines()
    return " | ".join(lines[-3:]) or "no output"


def _require_cookiecutter(python: str) -> None:
    try:
        ok = _run([python, "-c", "import cookiecutter"], Path.cwd(), GIT_TIMEOUT).returncode == 0
    except (OSError, subprocess.TimeoutExpired):
        ok = False
    if not ok:
        raise UpgradeError(
            E_NO_COOKIECUTTER,
            f"cookiecutter is not installed for {python}; "
            f"run `{python} -m pip install cookiecutter`",
        )


def _checkout(clone: Path, sha: str, dest: Path) -> None:
    result = _run(["git", "worktree", "add", "--quiet", "--detach", str(dest), sha], clone, 120)
    if result.returncode != 0:
        raise UpgradeError(E_CHECKOUT, f"template has no usable commit {sha}: {_tail(result)}")


def _render(python: str, source: Path, config: Path, out: Path, workdir: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    result = _run(
        [
            python, "-m", "cookiecutter", str(source), "--no-input",
            "--config-file", str(config), "--output-dir", str(out),
        ],
        workdir,
        RENDER_TIMEOUT,
    )
    if result.returncode != 0:
        raise UpgradeError(E_RENDER, f"rendering the template failed: {_tail(result)}")


def _diff_trees(old: Path, new: Path, scratch: Path) -> tuple[str, list[dict[str, str]]]:
    """Diff two directory trees with repo-relative paths, using a throwaway git repo."""
    # Isolate from the user's git config: signing, hooks and global ignores must not
    # change what the scratch repository records.
    git = [
        "git", "-c", "user.name=upgrade", "-c", "user.email=upgrade@invalid",
        "-c", "core.autocrlf=false", "-c", "commit.gpgsign=false",
        "-c", "core.excludesFile=/dev/null", "-c", "core.hooksPath=/dev/null",
    ]

    def step(*args: str) -> str:
        result = _run([*git, *args], scratch, GIT_TIMEOUT)
        if result.returncode != 0:
            raise UpgradeError(
                E_RENDER, f"comparing the renders failed (git {args[0]}): {_tail(result)}"
            )
        return result.stdout

    scratch.mkdir(parents=True)
    step("init", "--quiet")
    shutil.copytree(old, scratch, ignore=_ignored(old), symlinks=True, dirs_exist_ok=True)
    step("add", "-A", "-f")
    step("commit", "--quiet", "--allow-empty", "-m", "old")
    for entry in scratch.iterdir():
        if entry.name == ".git":
            continue
        shutil.rmtree(entry) if entry.is_dir() and not entry.is_symlink() else entry.unlink()
    shutil.copytree(new, scratch, ignore=_ignored(new), symlinks=True, dirs_exist_ok=True)
    step("add", "-A", "-f")
    flags = ["diff", "--cached", "--no-renames", "--no-color"]
    patch = step(*flags, "--binary", "--full-index", "HEAD")
    # NUL-separated, so unusual file names are not quoted by git.
    tokens = step(*flags, "--name-status", "-z", "HEAD").split("\0")
    files = [
        {"path": tokens[i + 1], "status": tokens[i]}
        for i in range(0, len(tokens) - 1, 2)
        if tokens[i]
    ]
    return patch, files


def build_patch(
    root: Path,
    upgrade_plan: dict[str, Any],
    workdir: Path,
    *,
    python: str | None = None,
) -> dict[str, Any]:
    """Render the old and new template with the stored answers and diff the results.

    Nothing in ``root`` is touched; everything is created under ``workdir``, which
    the caller removes. The patch uses repo-relative paths, so it applies with
    ``git apply --3way`` from the repository root.
    """
    if not upgrade_plan.get("ok"):
        raise UpgradeError(E_NOT_READY, "the upgrade plan has refusals; resolve them first")
    info = upgrade_plan["plan"]
    if info["up_to_date"]:
        return {"patch": None, "files": [], "old_tree": None, "new_tree": None}

    python = python or sys.executable
    _require_cookiecutter(python)
    root, workdir = Path(root).resolve(), Path(workdir).resolve()
    stamp, refusal = _read_stamp(root)
    if refusal:
        raise UpgradeError(refusal.code, refusal.message)
    context = stamp["context"]["cookiecutter"]
    repo_name = context["repo_name"]

    workdir.mkdir(parents=True, exist_ok=True)
    config = workdir / "cookiecutter.yaml"
    config.write_text(yaml.safe_dump({"default_context": context}), encoding="utf-8")

    clone = workdir / "template"
    cloned = _run(["git", "clone", "--quiet", "--no-checkout", "--",
                   _location(root, info["template"]), str(clone)],
                  workdir, 300)
    if cloned.returncode != 0:
        raise UpgradeError(E_CHECKOUT, f"cannot clone {info['template']}: {_tail(cloned)}")

    trees = {}
    for label in ("old", "new"):
        source = workdir / f"source-{label}"
        _checkout(clone, info[label], source)
        _render(python, source, config, workdir / f"render-{label}", workdir)
        trees[label] = workdir / f"render-{label}" / repo_name

    patch, files = _diff_trees(trees["old"], trees["new"], workdir / "compare")
    patch_path = workdir / "upgrade.patch"
    patch_path.write_text(patch, encoding="utf-8")
    return {
        "patch": str(patch_path) if patch else None,
        "files": files,
        "old_tree": str(trees["old"]),
        "new_tree": str(trees["new"]),
    }


def _git_dir(root: Path) -> Path:
    out = _run(["git", "rev-parse", "--absolute-git-dir"], root, GIT_TIMEOUT)
    if out.returncode != 0:
        raise UpgradeError(E_NOT_GIT, "not a git repository")
    return Path(out.stdout.strip())


def _import_base_blobs(root: Path, old_tree: Path, files: list[dict[str, str]]) -> None:
    """Store the old render's files as git objects so `git apply --3way` has a merge base.

    Without the base blob, a file the author edited cannot be merged and the apply
    fails instead. This only adds unreachable objects; the working tree is untouched.
    """
    for entry in files:
        source = old_tree / entry["path"]
        if entry["status"] in ("M", "D") and source.is_file():
            _run(["git", "hash-object", "-w", "--", str(source)], root, GIT_TIMEOUT)


def _split_patch(patch: str) -> list[str]:
    return [chunk for chunk in re.split(r"(?m)^(?=diff --git )", patch) if chunk.strip()]


def _unmerged(root: Path, path: str) -> bool:
    return bool(_run(["git", "ls-files", "-u", "--", path], root, GIT_TIMEOUT).stdout.strip())


def _apply_chunk(root: Path, chunk: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["git", "apply", "--3way", "-"],
        cwd=root,
        input=chunk,
        capture_output=True,
        text=True,
        timeout=GIT_TIMEOUT,
    )


def apply(
    root: Path, new_ref: str | None = None, *, python: str | None = None, commit: bool = False
) -> dict[str, Any]:
    """Apply the template changes on a new branch. Conflicts are left for the author.

    Never resolves a conflict. Writes ``upgrade-state.json`` in the git directory for
    ``finish``; the ``template.json`` stamp is untouched until then. With ``commit=True``
    (for CI) it also commits the result, conflict markers included, together with a
    tracked ``.upgrade-state.json`` so that a checkout of the branch can run ``finish``.
    """
    root = Path(root).resolve()
    upgrade_plan = plan(root, new_ref)
    if not upgrade_plan["ok"]:
        codes = ", ".join(r["code"] for r in upgrade_plan["refusals"])
        raise UpgradeError(
            E_NOT_READY, f"the upgrade plan has refusals ({codes}); resolve them first"
        )
    info = upgrade_plan["plan"]
    if info["up_to_date"]:
        return {"ok": True, "command": "upgrade", "up_to_date": True, "branch": None,
                "applied": [], "conflicted": [], "skipped": []}

    branch = f"upgrade/{info['new'][:8]}"
    if _run(["git", "rev-parse", "--verify", "--quiet", f"refs/heads/{branch}"], root,
            GIT_TIMEOUT).returncode == 0:
        raise UpgradeError(
            E_BRANCH_EXISTS, f"branch {branch} already exists; delete it or finish it"
        )

    original = _run(["git", "rev-parse", "--abbrev-ref", "HEAD"], root, GIT_TIMEOUT).stdout.strip()
    if original == "HEAD":
        original = _run(["git", "rev-parse", "HEAD"], root, GIT_TIMEOUT).stdout.strip()
    try:
        return _apply_changes(root, upgrade_plan, branch, python, commit)
    except BaseException as exc:
        _rollback(root, original, branch)
        if isinstance(exc, (OSError, subprocess.TimeoutExpired)):
            raise UpgradeError(E_RENDER, f"the upgrade failed and was rolled back: {exc}") from exc
        raise


def _rollback(root: Path, original: str, branch: str) -> None:
    """Undo a failed apply: back to the starting branch, with the half-made branch removed."""
    head = _run(["git", "rev-parse", "--abbrev-ref", "HEAD"], root, GIT_TIMEOUT).stdout.strip()
    if head != branch:
        return  # the branch was never created or entered
    _run(["git", "reset", "--hard", "--quiet"], root, GIT_TIMEOUT)
    _run(["git", "switch", "--quiet", "--detach", original]
         if re.fullmatch(r"[0-9a-f]{40}", original) else ["git", "switch", "--quiet", original],
         root, GIT_TIMEOUT)
    _run(["git", "branch", "-D", "--quiet", branch], root, GIT_TIMEOUT)
    (_git_dir(root) / STATE_NAME).unlink(missing_ok=True)


def _apply_changes(
    root: Path, upgrade_plan: dict[str, Any], branch: str, python: str | None, commit: bool
) -> dict[str, Any]:
    info = upgrade_plan["plan"]
    with tempfile.TemporaryDirectory(prefix="article-upgrade-") as tmp:
        built = build_patch(root, upgrade_plan, Path(tmp) / "work", python=python)
        files = built["files"]
        patch = Path(built["patch"]).read_text(encoding="utf-8") if built["patch"] else ""
        new_stamp = json.loads((Path(built["new_tree"]) / STAMP_NAME).read_text(encoding="utf-8"))
        chunks = _split_patch(patch)
        if len(chunks) != len(files):
            raise UpgradeError(E_RENDER, "patch and file list disagree; refusing to apply")
        _import_base_blobs(root, Path(built["old_tree"]), files)

        switched = _run(["git", "switch", "--quiet", "-c", branch], root, GIT_TIMEOUT)
        if switched.returncode != 0:
            raise UpgradeError(
                E_BRANCH_EXISTS, f"cannot create branch {branch}: {_tail(switched)}"
            )

        applied, conflicted, skipped = [], [], []
        for entry, chunk in zip(files, chunks, strict=True):
            path, status = entry["path"], entry["status"]
            target = root / path
            if status == "A" and target.exists():
                new_file = Path(built["new_tree"]) / path
                same = new_file.is_file() and target.read_bytes() == new_file.read_bytes()
                skipped.append({
                    "path": path,
                    "reason": "already present with the new content" if same
                    else "exists locally with different content; merge it by hand",
                })
                continue
            result = _apply_chunk(root, chunk)
            if result.returncode == 0:
                applied.append(path)
            elif _unmerged(root, path):
                conflicted.append(path)
            else:
                skipped.append({"path": path, "reason": _tail(result)})

    state = json.dumps({
        "branch": branch, "old": info["old"], "new": info["new"],
        "new_template_version": new_stamp.get("template_version"),
        "new_template_commit": new_stamp.get("template_commit"),
        "files": [f["path"] for f in files],
    })
    (_git_dir(root) / STATE_NAME).write_text(state, encoding="utf-8")
    if commit:
        _commit_upgrade(root, state, info)
    return {"ok": not conflicted, "command": "upgrade", "up_to_date": False, "branch": branch,
            "applied": applied, "conflicted": conflicted, "skipped": skipped,
            "committed": commit}


def _commit_upgrade(root: Path, state: str, info: dict[str, Any]) -> None:
    (root / TRACKED_STATE).write_text(state + "\n", encoding="utf-8")
    # Conflict markers are committed on purpose: the PR is where they get resolved.
    _run(["git", "add", "-A"], root, GIT_TIMEOUT)
    message = f"chore: upgrade from template {info['old'][:8]} to {info['new'][:8]}"
    result = _run(["git", "commit", "--quiet", "-m", message], root, GIT_TIMEOUT)
    if result.returncode != 0:
        raise UpgradeError(
            E_COMMIT, f"cannot commit the upgrade (is user.name/user.email set?): {_tail(result)}"
        )


def _metadata_drift(root: Path) -> list[str]:
    """Derived files whose content differs from what metadata.yaml would generate."""
    from .metadata import collect_expected, compare_outputs, load_metadata

    try:
        metadata = load_metadata(root / "metadata.yaml")
        expected = collect_expected(root, metadata)
    except (FileNotFoundError, ValueError):
        return []  # `make metadata` reports this with its own message
    return sorted(item.path for item in compare_outputs(root, expected))


def finish(root: Path, *, regenerate: bool = False) -> dict[str, Any]:
    """Check the resolved upgrade, regenerate derived files and bump the stamp.

    Refuses while any path is unmerged or still has conflict markers. Also refuses when a
    derived file differs from what metadata.yaml generates, because regenerating would
    silently overwrite the author's hand edits; ``regenerate=True`` accepts that. Leaves
    the result staged for the author to commit.
    """
    root = Path(root).resolve()
    state_path = _git_dir(root) / STATE_NAME
    tracked = root / TRACKED_STATE
    source = state_path if state_path.is_file() else tracked
    if not source.is_file():
        raise UpgradeError(E_NO_UPGRADE, "no upgrade in progress; run `upgrade --apply` first")
    state = json.loads(source.read_text(encoding="utf-8"))
    current = _run(["git", "rev-parse", "--abbrev-ref", "HEAD"], root, GIT_TIMEOUT).stdout.strip()
    if current != state["branch"]:
        raise UpgradeError(
            E_WRONG_BRANCH, f"switch back to {state['branch']} to finish the upgrade"
        )

    unmerged = sorted({line.split("\t")[-1] for line in
                       _run(["git", "ls-files", "-u"], root, GIT_TIMEOUT).stdout.splitlines()})
    marked = []
    for path in state["files"]:
        file = root / path
        if file.is_file():
            text = file.read_text(encoding="utf-8", errors="replace")
            if re.search(r"(?m)^(<{7}|>{7})( |$)", text):
                marked.append(path)
    if unmerged or marked:
        raise UpgradeError(
            E_CONFLICTS,
            "unresolved conflicts in: " + ", ".join(sorted(set(unmerged) | set(marked))),
        )

    drifted = [] if regenerate else _metadata_drift(root)
    if drifted:
        raise UpgradeError(
            E_DRIFT,
            "these files differ from what metadata.yaml generates, so `make metadata` would "
            "overwrite them: " + ", ".join(drifted) + ". Put the edits into metadata.yaml, "
            "or run `upgrade --finish --regenerate` to overwrite them.",
        )

    for target in ("metadata", "validate"):
        result = _run(["make", target], root, RENDER_TIMEOUT)
        if result.returncode != 0:
            raise UpgradeError(E_CHECKS_FAILED, f"`make {target}` failed: {_tail(result)}")

    stamp_path = root / STAMP_NAME
    stamp = json.loads(stamp_path.read_text(encoding="utf-8"))
    stamp["template_version"] = state["new_template_version"] or stamp.get("template_version")
    stamp["template_commit"] = state["new_template_commit"] or state["new"]
    stamp_path.write_text(
        json.dumps(stamp, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    state_path.unlink(missing_ok=True)
    tracked.unlink(missing_ok=True)
    _run(["git", "add", "-A"], root, GIT_TIMEOUT)
    return {
        "ok": True, "command": "upgrade", "finished": True,
        "branch": state["branch"], "template_commit": stamp["template_commit"],
    }
