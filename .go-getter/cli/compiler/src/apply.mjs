// The generated GitHub Actions workflow: the tier-3 guardrail job (decision 0009) when `guardrails`, and one job per
// check placed in CI (`ci` or `both`, decision 0071). `node` is {version, install} for a Node project, else null;
// `branch` is the project's default branch, whose pushes the workflow also runs on.
export function ciWorkflow({ guardrails = true, checks = {}, node = null, branch = 'main' } = {}) {
  const lines = [
    '# Generated by go-getter apply; do not edit. Tier-3 guardrail checks (decision 0009) and CI-placed verification checks (decision 0071).',
    'name: go-getter checks',
    '',
    'on:',
    '  pull_request:',
    '  push:',
    `    branches: [${scalar(branch)}]`,
    '',
    'permissions:',
    '  contents: read',
    '',
    'jobs:',
  ];
  if (guardrails) {
    lines.push(
      '  go-getter-checks:',
      '    runs-on: ubuntu-latest',
      '    steps:',
      `      - uses: ${CHECKOUT}`,
      '        with:',
      '          fetch-depth: 0',
      `      - uses: ${SETUP_NODE}`,
      '        with:',
      `          node-version: ${NODE_FLOOR}`,
      `      - run: sh ${RUNNER} check --stage ci`,
    );
  }
  for (const [name, command] of Object.entries(checks)) {
    if (lines.at(-1) !== 'jobs:') lines.push('');
    lines.push(`  verify-${name}:`, '    runs-on: ubuntu-latest', '    steps:', `      - uses: ${CHECKOUT}`);
    if (node) {
      lines.push(`      - uses: ${SETUP_NODE}`, '        with:', `          node-version: ${scalar(node.version)}`);
      if (node.install) lines.push(`      - run: ${scalar(node.install)}`);
    }
    lines.push(`      - run: ${scalar(command)}`);
  }
  return `${lines.join('\n')}\n`;
}

// The branch whose pushes the workflow runs on. A remote that names its default branch decides; without one (a CI
// checkout of a pull request is detached) the branch the committed workflow already names stays, so the workflow does
// not change with where apply runs. Failing both, the checked-out branch if it is main or master, else main.
function workflowBranch(project, detected) {
  if (detected.git?.defaultBranchKnown) return detected.git.defaultBranch;
  try {
    const m = /^    branches: \[(.*)\]$/m.exec(readFileSync(path.join(project, '.github/workflows/go-getter-checks.yml'), 'utf8'));
    if (m) return m[1].startsWith('"') ? JSON.parse(m[1]) : m[1];
  } catch {
    // no workflow yet
  }
  return ['main', 'master'].includes(detected.git?.defaultBranch) ? detected.git.defaultBranch : 'main';
}

