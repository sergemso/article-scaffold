export function pluginDir(packageRoot) {
  const own = path.join(packageRoot, 'plugins/go-getter');
  if (existsSync(own)) return own;
  const bundled = path.resolve(packageRoot, '..', '..', '..');
  return path.basename(packageRoot) === 'cli' && existsSync(path.join(bundled, 'skills')) ? bundled : own;
}

