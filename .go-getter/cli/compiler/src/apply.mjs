function guardrailSection(entries) {
  const byGuardrail = new Map();
  for (const e of entries) {
    const g = byGuardrail.get(e.guardrail) ?? { title: e.title, tiers: new Set() };
    g.tiers.add(e.tier);
    byGuardrail.set(e.guardrail, g);
  }
  const groups = { 3: [], 2: [], 1: [] };
  for (const [id, g] of [...byGuardrail].sort()) groups[Math.max(...g.tiers)].push(`- ${g.title} (\`${id}\`)`);
  const lines = [MARK_START, '## Guardrails', '', 'Generated by `go-getter apply` from `docs/guardrails/`; do not edit this section.', ''];
  if (groups[3].length) lines.push('Checked by git hooks and CI:', '', ...groups[3], '');
  if (groups[2].length) lines.push('Blocked by host hooks where the host supports it:', '', ...groups[2], '');
  if (groups[1].length) lines.push('Advisory:', '', ...groups[1], '');
  lines.push(MARK_END);
  return lines.join('\n');
}

export function withSection(existing, section) {
  if (existing.includes(MARK_START) && existing.includes(MARK_END)) {
    const start = existing.indexOf(MARK_START);
    const end = existing.indexOf(MARK_END) + MARK_END.length;
    return existing.slice(0, start) + section + existing.slice(end);
  }
  return `${existing.replace(/\n*$/, '')}${existing.trim() ? '\n\n' : ''}${section}\n`;
}

