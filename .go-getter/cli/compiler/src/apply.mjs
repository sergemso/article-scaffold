// Recognises go-getter's hook entries in both command shapes (the old relative `sh <runner> hook` and the walk-up one that quotes the path).
const HOOK_TAG = new RegExp(`${RUNNER.replaceAll('.', '\\.')}(\\\\")? hook`);
const NODE_FLOOR = 22;

// The npx source of the CLI: pinned to the release tag of the package that wrote the runner (decision 0023), unpinned
// for an unreleased 0.0.0 build, which has no tag.
const CLI_SOURCE = 'github:vivantel/go-getter';
// Where the runner restores a missing CLI copy from (plain git, which npm's allow-git setting does not govern).
const CLI_REPO = 'https://github.com/vivantel/go-getter.git';

export function runnerScript(version) {
  const released = version && version !== '0.0.0';
  const source = released ? `${CLI_SOURCE}#v${version}` : CLI_SOURCE;
  // The CLI copy is gitignored, so a fresh clone or worktree lacks it. Restore it from the release tag with plain git
  // before npx, which npm 12 refuses for git sources (EALLOWGIT). An unreleased build has no tag and skips this.
  const restore = released
    ? `if command -v git >/dev/null 2>&1; then
  TMP=$(mktemp -d 2>/dev/null) && if git clone --quiet --depth 1 --branch v${version} "\${GO_GETTER_REPO:-${CLI_REPO}}" "$TMP/cli" >/dev/null 2>&1 \
    && [ -f "$TMP/cli/compiler/bin/go-getter.mjs" ] && mkdir -p "$ROOT/.go-getter" && rm -rf "$TMP/cli/.git" && mv "$TMP/cli" "$ROOT/${VENDORED_CLI}" 2>/dev/null; then
    echo "go-getter: restored the CLI copy in ${VENDORED_CLI} (v${version})" >&2
  fi
  [ -z "$TMP" ] || rm -rf "$TMP"
fi
if [ -f "$ROOT/${VENDORED_CLI}/compiler/bin/go-getter.mjs" ]; then
  exec node "$ROOT/${VENDORED_CLI}/compiler/bin/go-getter.mjs" "$@"
fi
`
    : '';
  return `#!/bin/sh
# Generated by go-getter apply; do not edit. Runs the go-getter CLI when Node >= ${NODE_FLOOR} is available,
# otherwise warns and exits 0 so enforcement degrades to advisory (decision 0019).
# Order: a go-getter checkout, GO_GETTER_CLI (compiler/bin/go-getter.mjs of a checkout), the CLI copy in ${VENDORED_CLI}, then a restore from the release tag, then npx.
FLOOR=${NODE_FLOOR}
if ! command -v node >/dev/null 2>&1; then
  echo "go-getter: enforcement unavailable: Node >= $FLOOR not found" >&2
  exit 0
fi
MAJOR=$(node -p 'process.versions.node.split(".")[0]')
if [ "$MAJOR" -lt "$FLOOR" ]; then
  echo "go-getter: enforcement unavailable: Node $MAJOR < $FLOOR" >&2
  exit 0
fi
ROOT=$(git rev-parse --show-toplevel 2>/dev/null || pwd)
if [ -f "$ROOT/compiler/bin/go-getter.mjs" ] && grep -q '"name": "go-getter"' "$ROOT/package.json" 2>/dev/null; then
  exec node "$ROOT/compiler/bin/go-getter.mjs" "$@"
fi
if [ -n "$GO_GETTER_CLI" ]; then
  if [ -f "$GO_GETTER_CLI" ]; then
    exec node "$GO_GETTER_CLI" "$@"
  fi
  echo "go-getter: GO_GETTER_CLI=$GO_GETTER_CLI is not a file; trying npx" >&2
fi
if [ -f "$ROOT/${VENDORED_CLI}/compiler/bin/go-getter.mjs" ]; then
  exec node "$ROOT/${VENDORED_CLI}/compiler/bin/go-getter.mjs" "$@"
fi
${restore}# This is go-getter's own pinned source, so allow git for this one call (npm 12 defaults to allow-git=none).
export npm_config_allow_git="\${npm_config_allow_git:-all}"
ERR=$(mktemp 2>/dev/null) || exec npx --yes ${source} "$@"
npx --yes ${source} "$@" 2>"$ERR"
CODE=$?
cat "$ERR" >&2
if [ "$CODE" -ne 0 ] && grep -q '^npm error' "$ERR"; then
  echo "go-getter: npx could not run the CLI (npm error above), so this call was not enforced. Re-run go-getter apply to vendor a CLI copy into ${VENDORED_CLI}, set GO_GETTER_CLI to compiler/bin/go-getter.mjs of a go-getter checkout, or allow git fetches for npm (npm_config_allow_git=all)." >&2
fi
rm -f "$ERR"
exit $CODE
`;
}

