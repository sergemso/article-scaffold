// Reading a shell command, and recognising a go-getter call by what it runs (decision 0126). go-getter may be installed per
// project (`.go-getter/bin/go-getter`), per user (a `go-getter` on PATH or an entry under the home directory), through `npx`, or run
// as `node <entry>`; every feature that recognises "a go-getter call" asks here, so none depends on how the call is spelled.
import { existsSync, openSync, readSync, closeSync, readFileSync, realpathSync, statSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';

// --- the tokenizer -------------------------------------------------------------------------------------------------------

// Splits `command` into the words of ONE simple command: quotes and escapes are resolved, so `a "b c"` is two words. It is a
// simple command only when nothing else could run in it: no pipe, list, background, redirect, heredoc, comment, subshell,
// substitution or variable expansion outside single quotes, and no leading `NAME=value` assignment. Otherwise `simple` is false
// and `reason` says why; `words` is then the best effort and must not be trusted.
export function parseSimpleCommand(command) {
  const words = [];
  let word = null;
  let i = 0;
  const text = String(command);
  const fail = (reason) => ({ simple: false, reason, words });
  const push = () => {
    if (word !== null) words.push(word);
    word = null;
  };
  while (i < text.length) {
    const ch = text[i];
    if (ch === "'") {
      const end = text.indexOf("'", i + 1);
      if (end < 0) return fail('an unterminated quote');
      word = (word ?? '') + text.slice(i + 1, end);
      i = end + 1;
    } else if (ch === '"') {
      let j = i + 1;
      let part = '';
      for (; j < text.length && text[j] !== '"'; j++) {
        if (text[j] === '\\' && j + 1 < text.length && '"\\$`\n'.includes(text[j + 1])) part += text[++j];
        else if (text[j] === '$' || text[j] === '`') return fail('an expansion inside double quotes');
        else part += text[j];
      }
      if (j >= text.length) return fail('an unterminated quote');
      word = (word ?? '') + part;
      i = j + 1;
    } else if (ch === '\\') {
      if (i + 1 >= text.length) return fail('a trailing backslash');
      if (text[i + 1] === '\n') {
        i += 2; // a line continuation
        continue;
      }
      word = (word ?? '') + text[i + 1];
      i += 2;
    } else if (ch === ' ' || ch === '\t') {
      push();
      i++;
    } else if ('\n;|&<>()`'.includes(ch)) {
      return fail(ch === '\n' ? 'a second line' : `the operator ${ch}`);
    } else if (ch === '$') {
      return fail('an expansion');
    } else if (ch === '#' && word === null) {
      return fail('a comment');
    } else {
      word = (word ?? '') + ch;
      i++;
    }
  }
  push();
  if (!words.length) return fail('an empty command');
  if (/^[A-Za-z_][A-Za-z0-9_]*=/.test(words[0])) return fail('a leading variable assignment');
  return { simple: true, words };
}

// --- recognising go-getter -----------------------------------------------------------------------------------------------

const RUNNER_MARKER = 'Generated by go-getter apply';
const NPX_PACKAGE = /^(?:go-getter(?:@[\w.+-]+)?|(?:github:)?vivantel\/go-getter(?:#[\w./-]+)?)$/;

function head(file, bytes = 400) {
  const fd = openSync(file, 'r');
  try {
    const buf = Buffer.alloc(bytes);
    return buf.subarray(0, readSync(fd, buf, 0, bytes, 0)).toString('utf8');
  } finally {
    closeSync(fd);
  }
}

// The package name above `file`, looking up at most `levels` directories.
function packageNameAbove(file, levels = 4) {
  let dir = path.dirname(file);
  for (let n = 0; n < levels; n++, dir = path.dirname(dir)) {
    const manifest = path.join(dir, 'package.json');
    if (existsSync(manifest)) {
      try {
        return JSON.parse(readFileSync(manifest, 'utf8')).name;
      } catch {
        return undefined;
      }
    }
    if (dir === path.dirname(dir)) break;
  }
  return undefined;
}

// Whether `file` is a go-getter entry: the runner `apply` generates (identified by its marker line) or a go-getter package's
// entry script, after following any symlink (a global install links its bin name to the package).
export function isGoGetterEntry(file) {
  let real;
  try {
    real = realpathSync(file);
    if (!statSync(real).isFile()) return false;
  } catch {
    return false;
  }
  const base = path.basename(real);
  if (base === 'go-getter') {
    try {
      return head(real).includes(RUNNER_MARKER);
    } catch {
      return false;
    }
  }
  return /^go-getter\.mjs$/.test(base) && packageNameAbove(real) === 'go-getter';
}

const expandHome = (file) => (file === '~' || file.startsWith('~/') ? path.join(os.homedir(), file.slice(1)) : file);

// The file a word names as a program: a path (relative to `cwd`) or a bare name looked up on PATH; null when there is none.
function programFile(word, cwd, env) {
  if (word.includes('/') || word.startsWith('~')) return path.resolve(cwd, expandHome(word));
  for (const dir of String(env.PATH ?? '').split(path.delimiter).filter(Boolean)) {
    const candidate = path.join(dir, word);
    if (existsSync(candidate)) return candidate;
  }
  return null;
}

// `{ via, args }` when the words of a simple command run go-getter, else null; `args` are go-getter's own arguments (so
// `args[0]` is its subcommand). `via` is how it was reached: `runner`, `path`, `npx` or `node`.
//   go-getter ...            a go-getter on PATH
//   ./.go-getter/bin/go-getter ..., ~/tools/go-getter/compiler/bin/go-getter.mjs ...   a path to an entry
//   npx [-y] go-getter ..., npx github:vivantel/go-getter ...
//   node [flags] <entry> ...
export function goGetterCall(words, { cwd = process.cwd(), env = process.env } = {}) {
  if (!Array.isArray(words) || !words.length) return null;
  const [first, ...rest] = words;
  if (first === 'npx') {
    let k = 0;
    while (k < rest.length && /^-/.test(rest[k]) && !/^--?(?:p|package)(?:=|$)/.test(rest[k])) k++;
    return k < rest.length && NPX_PACKAGE.test(rest[k]) ? { via: 'npx', args: rest.slice(k + 1) } : null;
  }
  if (first === 'node') {
    let k = 0;
    while (k < rest.length && /^-/.test(rest[k])) k++;
    const file = rest[k] && path.resolve(cwd, expandHome(rest[k]));
    return file && isGoGetterEntry(file) ? { via: 'node', args: rest.slice(k + 1) } : null;
  }
  const file = programFile(first, cwd, env);
  if (!file || !isGoGetterEntry(file)) return null;
  return { via: file.split(path.sep).slice(-3).join('/') === '.go-getter/bin/go-getter' ? 'runner' : 'path', args: rest };
}

// `{ via, args }` when `command` is exactly one simple command that runs go-getter, else null.
export function goGetterCommand(command, options) {
  const parsed = parseSimpleCommand(command);
  return parsed.simple ? goGetterCall(parsed.words, options) : null;
}
